def _create_audit_partitions() -> None:
    """audit_logs e particionada por mes: expurgo vira DROP PARTITION (secao 16).

    A funcao cria a particao do mes indicado de forma idempotente; o cron mensal
    chama `orbi maintenance partitions`.
    """
    op.execute(
        """
        CREATE OR REPLACE FUNCTION orbi_ensure_audit_partition(target date)
        RETURNS text
        LANGUAGE plpgsql
        AS $$
        DECLARE
            start_date date := date_trunc('month', target)::date;
            end_date   date := (date_trunc('month', target) + interval '1 month')::date;
            part_name  text := 'audit_logs_' || to_char(start_date, 'YYYYMM');
        BEGIN
            IF NOT EXISTS (SELECT 1 FROM pg_class WHERE relname = part_name) THEN
                EXECUTE format(
                    'CREATE TABLE %I PARTITION OF audit_logs FOR VALUES FROM (%L) TO (%L)',
                    part_name, start_date, end_date
                );
                EXECUTE format('GRANT SELECT, INSERT ON %I TO orbi_app', part_name);
                EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', part_name);
                EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', part_name);
            END IF;
            RETURN part_name;
        END;
        $$
        """
    )
