def _enable_row_level_security() -> None:
    """Isolamento total entre tenants (ORBI.md secao 11).

    A politica le `app.tenant_id`, definido por `SET LOCAL` na unica dependency
    que abre sessao. Sem o SET, a politica nao casa e a consulta devolve zero
    linhas — falha fechada, nunca aberta.
    """
    for table in TENANT_SCOPED_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"""
            CREATE POLICY {table}_tenant_isolation ON {table}
            USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
            WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid)
            """
        )

    # A tabela de tenants se isola pelo proprio id.
    op.execute("ALTER TABLE tenants ENABLE ROW LEVEL SECURITY")
    op.execute("ALTER TABLE tenants FORCE ROW LEVEL SECURITY")
    op.execute(
        """
        CREATE POLICY tenants_tenant_isolation ON tenants
        USING (id = nullif(current_setting('app.tenant_id', true), '')::uuid)
        WITH CHECK (id = nullif(current_setting('app.tenant_id', true), '')::uuid)
        """
    )

    # audit_logs e append-only: UPDATE e DELETE revogados no banco (secao 11).
    op.execute(f"REVOKE UPDATE, DELETE, TRUNCATE ON audit_logs FROM {APP_ROLE}")
    op.execute(
        """
        CREATE OR REPLACE FUNCTION orbi_audit_logs_append_only()
        RETURNS trigger
        LANGUAGE plpgsql
        AS $$
        BEGIN
            RAISE EXCEPTION 'audit_logs e append-only: % nao e permitido', TG_OP;
        END;
        $$
        """
    )
    op.execute(
        """
        CREATE TRIGGER audit_logs_append_only
        BEFORE UPDATE OR DELETE ON audit_logs
        FOR EACH ROW EXECUTE FUNCTION orbi_audit_logs_append_only()
        """
    )


